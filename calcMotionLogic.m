function [motionScore, highestY] = calcMotionLogic(bgImg, currImg, minPixRow)
% CALCMOTIONLOGIC מנתח תנועה באזור ממוקד (ROI) ומוצא את קצה הגוף העליון.
%   הפונקציה מבצעת חיסור רקע אך מתמקדת רק בשליש האמצעי של התמונה (כדי
%   להתעלם מתנועות ידיים בצדדים), ומחזירה את מיקום "הראש" (הנקודה הגבוהה
%   ביותר שזזה).
%
%   INPUTS:
%       bgImg     - תמונת הרקע (Background Reference).
%       currImg   - הפריים הנוכחי.
%       minPixRow - (אופציונלי) סף פיקסלים מינימלי בשורה כדי להחשיבה כחלק מהגוף.
%
%   OUTPUTS:
%       motionScore - מדד עוצמת התנועה באזור העניין.
%       highestY    - אינדקס השורה הגבוהה ביותר (Y מינימלי) בה זוהתה תנועה.

    % ====================================================================
    % 1. אתחול והמרת פורמטים
    % ====================================================================
    
    if nargin < 3
        minPixRow = 10; % ערך ברירת מחדל
    end
    
    motionScore = 0; 
    highestY = []; 
    
    % המרה ל-Double ולגווני אפור לצורך חישוב הפרשים מדויק
    if size(bgImg, 3) == 3
        bg = double(rgb2gray(bgImg)); 
    else
        bg = double(bgImg); 
    end
    
    if size(currImg, 3) == 3
        curr = double(rgb2gray(currImg)); 
    else
        curr = double(currImg); 
    end
    
    % ====================================================================
    % 2. הגדרת אזור עניין (Region of Interest - ROI)
    % ====================================================================
    
    [rows, cols] = size(bg);
    
    % חישוב הגבולות האופקיים: התמקדות ב-30% האמצעיים של רוחב התמונה.
    % המטרה: להתמקד בעליית הראש/גוף ולהתעלם מתנועות ידיים/מרפקים בצדדים.
    xStart = max(1, round(cols * 0.35)); 
    xEnd   = min(cols, round(cols * 0.65));
    
    % יצירת מסכה לוגית עבור ה-ROI
    roiMask = false(rows, cols); 
    roiMask(:, xStart:xEnd) = true;
    
    % ====================================================================
    % 3. זיהוי תנועה וסינון רעשים
    % ====================================================================
    
    % חישוב ההפרש המוחלט
    diffFrame = abs(curr - bg);
    
    % יצירת מסכה בינארית משולבת:
    % 1. פיקסלים שהשתנו מעל סף הרגישות (45).
    % 2. פיקסלים שנמצאים בתוך ה-ROI שהגדרנו.
    mask = (diffFrame > 45) & roiMask; 
    
    % ניקוי רעשים מורפולוגי (הסרת כתמים קטנים מ-100 פיקסלים)
    mask = bwareaopen(mask, 100); 
    
    % ====================================================================
    % 4. חילוץ נתונים (Feature Extraction)
    % ====================================================================
    
    % א. ציון תנועה כללי (סכום הפיקסלים הלבנים במסכה)
    motionScore = sum(mask(:));
    
    % ב. מציאת הנקודה הגבוהה ביותר (מיקום הראש):
    % סכימת הפיקסלים הלבנים בכל שורה
    pixelsPerRow = sum(mask, 2);
    
    % מציאת השורות הרלוונטיות
    validRows = find(pixelsPerRow >= minPixRow);
    
    if ~isempty(validRows)
        % במטריצת תמונה, שורה 1 היא החלק העליון.
        % לכן האינדקס הראשון (המינימלי) מייצג את הנקודה הגבוהה ביותר פיזית.
        highestY = validRows(1); 
    end
    
end